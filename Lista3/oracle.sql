SELECT
    FUNKCJA AS "Funkcja",
    KOCURY.PSEUDO AS "Pseudonim kota",
    COUNT(*) "Liczba wrogow"
FROM KOCURY
JOIN WROGOWIE_KOCUROW ON KOCURY.PSEUDO = WROGOWIE_KOCUROW.PSEUDO
GROUP BY FUNKCJA, KOCURY.PSEUDO
HAVING COUNT(*) > 1;

SELECT
    FUNKCJA AS "Funkcja",
    KOCURY.PSEUDO AS "Pseudonim kota",
    COUNT(*) "Liczba wrogow"
FROM KOCURY
JOIN WROGOWIE_KOCUROW ON KOCURY.PSEUDO = WROGOWIE_KOCUROW.PSEUDO
JOIN WROGOWIE ON WROGOWIE_KOCUROW.IMIE_WROGA = WROGOWIE.IMIE_WROGA
GROUP BY FUNKCJA, KOCURY.PSEUDO
HAVING COUNT(CASE WHEN WROGOWIE.GATUNEK = 'CZLOWIEK' THEN 1 END) > 0
AND COUNT(CASE WHEN WROGOWIE.GATUNEK = 'PIES' THEN 1 END) > 0;

