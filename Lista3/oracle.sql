SELECT
    K1.PSEUDO AS "Pseudo",
    K1.PRZYDZIAL_MYSZY AS "Przydzial myszy",
    SUM(K2.PRZYDZIAL_MYSZY) / COUNT(DISTINCT WROGOWIE_KOCUROW.IMIE_WROGA) AS "Suma w bandzie",
    ROUND(K1.PRZYDZIAL_MYSZY / (SUM(K2.PRZYDZIAL_MYSZY) / COUNT(DISTINCT WROGOWIE_KOCUROW.IMIE_WROGA)) * 100) AS "Proc w bandzie"
FROM KOCURY K1
JOIN BANDY ON K1.NR_BANDY = BANDY.NR_BANDY
JOIN KOCURY K2 ON BANDY.NR_BANDY = K2.NR_BANDY
JOIN WROGOWIE_KOCUROW ON K1.PSEUDO = WROGOWIE_KOCUROW.PSEUDO
JOIN WROGOWIE ON WROGOWIE_KOCUROW.IMIE_WROGA = WROGOWIE.IMIE_WROGA
WHERE TEREN IN ('POLE', 'CALOSC')
AND WROGOWIE.STOPIEN_WROGOSCI BETWEEN 6 AND 10
GROUP BY K1.PSEUDO, K1.PRZYDZIAL_MYSZY;

