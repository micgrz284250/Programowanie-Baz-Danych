-- zadanie 2
SELECT
    COALESCE(KOCURY.PSEUDO, 'Brak przelozonego') AS "Przelozony",
    COALESCE(PODWLADNI.PSEUDO, 'Brak podwladnego') AS "Podwladny"
FROM KOCURY
FULL OUTER JOIN KOCURY PODWLADNI ON PODWLADNI.SZEF = KOCURY.PSEUDO
WHERE (KOCURY.PLEC = 'M'
    OR KOCURY.PSEUDO IS NULL)
AND (PODWLADNI.PLEC = 'M'
    OR PODWLADNI.PSEUDO IS NULL)
ORDER BY "Przelozony";

