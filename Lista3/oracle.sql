SELECT DISTINCT
    K1.IMIE AS "W stadzie przed szefem lub bez incydentu",
    CASE
        WHEN K1.W_STADKU_OD < JACEK.W_STADKU_OD THEN 'TAK'
        ELSE 'NIE'
    END AS "Czy dolaczyl przed JACKIEM"
FROM KOCURY K1
LEFT JOIN KOCURY K2 ON K1.SZEF = K2.PSEUDO
LEFT JOIN WROGOWIE_KOCUROW ON K1.PSEUDO = WROGOWIE_KOCUROW.PSEUDO
LEFT JOIN KOCURY JACEK ON JACEK.IMIE = 'JACEK'
WHERE (K1.W_STADKU_OD < K2.W_STADKU_OD
           AND WROGOWIE_KOCUROW.IMIE_WROGA LIKE '%A')
   OR WROGOWIE_KOCUROW.PSEUDO IS NULL;

