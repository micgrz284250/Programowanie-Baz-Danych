SELECT
    BANDY.NR_BANDY AS "Lepsze bandy",
    AVG(KOCURY.PRZYDZIAL_MYSZY + COALESCE(KOCURY.MYSZY_EXTRA, 0)) AS "Sredni przydzial w bandzie",
    ROUND((SELECT AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) FROM KOCURY), 1) AS "Sredni przydzial"
FROM BANDY
JOIN KOCURY ON BANDY.NR_BANDY = KOCURY.NR_BANDY
GROUP BY BANDY.NR_BANDY
HAVING AVG(KOCURY.PRZYDZIAL_MYSZY + COALESCE(KOCURY.MYSZY_EXTRA, 0)) > (SELECT AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) FROM KOCURY);

