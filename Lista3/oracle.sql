SELECT
    PSEUDO AS "Pseudonim",
    PRZYDZIAL_MYSZY AS "Zjada",
    NR_BANDY AS "Banda",
    'Prominent' AS "Typ",
    CASE
        WHEN PRZYDZIAL_MYSZY > 60 THEN 'Powyzej 60'
        ELSE 'Ponizej 60'
    END AS "Ocena"
FROM KOCURY
WHERE PRZYDZIAL_MYSZY > (SELECT AVG(PRZYDZIAL_MYSZY) FROM KOCURY)

UNION

SELECT
    K1.PSEUDO AS "Pseudonim",
    K1.PRZYDZIAL_MYSZY AS "Zjada",
    K1.NR_BANDY AS "Banda",
    'Szarak' AS "Typ",
    CASE
        WHEN PRZYDZIAL_MYSZY > 60 THEN 'Powyzej 60'
        ELSE 'Ponizej 60'
    END AS "Ocena"
FROM KOCURY K1
WHERE NOT EXISTS(SELECT
                     PSEUDO
                 FROM KOCURY K2
                 WHERE K2.PRZYDZIAL_MYSZY < K1.PRZYDZIAL_MYSZY
                 AND K2.NR_BANDY = K1.NR_BANDY);

-- z użyciem not exists
