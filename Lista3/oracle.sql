    AVG(KOCURY.PRZYDZIAL_MYSZY + COALESCE(KOCURY.MYSZY_EXTRA, 0)) AS "Sredni przydzial w bandzie",
    ROUND((SELECT AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) FROM KOCURY), 1) AS "Sredni przydzial"
