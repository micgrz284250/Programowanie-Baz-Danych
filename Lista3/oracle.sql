    K1.PSEUDO
FROM KOCURY K1
WHERE NOT EXISTS(SELECT
                     PSEUDO
                 FROM KOCURY K2
                 WHERE K2.SZEF = K1.PSEUDO)
ORDER BY K1.PSEUDO;

