SELECT
    NAZWA AS "Nazwa bandy",
    COUNT(DISTINCT KOCURY.PSEUDO) AS "Koty z wrogami"
FROM BANDY
JOIN KOCURY ON BANDY.NR_BANDY = KOCURY.NR_BANDY
JOIN WROGOWIE_KOCUROW ON KOCURY.PSEUDO = WROGOWIE_KOCUROW.PSEUDO
GROUP BY NAZWA;

