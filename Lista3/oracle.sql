SELECT
    TRIM(TO_CHAR(W_STADKU_OD, 'MONTH', 'NLS_DATE_LANGUAGE=ENGLISH')) AS "Miesiac",
    COUNT(*) AS "Liczba rekrutow"
FROM KOCURY
GROUP BY
    EXTRACT(MONTH FROM W_STADKU_OD),
    TO_CHAR(W_STADKU_OD, 'MONTH', 'NLS_DATE_LANGUAGE=ENGLISH')
ORDER BY EXTRACT(MONTH FROM W_STADKU_OD);

