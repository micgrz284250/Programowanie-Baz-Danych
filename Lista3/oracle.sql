SELECT
    LEVEL AS "Poziom",
    PSEUDO AS "Pseudonim",
    FUNKCJA AS "Funkcja",
    NR_BANDY AS "Nr bandy"
FROM KOCURY
WHERE PLEC = 'M'
START WITH FUNKCJA = 'BANDZIOR' AND PLEC = 'M'
CONNECT BY PRIOR PSEUDO = SZEF;

