SELECT
    LPAD(PSEUDO, LENGTH(PSEUDO) + (LEVEL - 1) * 2, ' ') AS "Pseudonim"
FROM KOCURY
START WITH PLEC = 'M'
       AND MONTHS_BETWEEN(DATE '2024-07-17', W_STADKU_OD) / 12 > 15
       AND COALESCE(MYSZY_EXTRA, 0) = 0
CONNECT BY PRIOR SZEF = PSEUDO;

