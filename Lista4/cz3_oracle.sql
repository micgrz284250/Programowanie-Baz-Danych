-- zadanie 9
SELECT
    PSEUDO AS "Do przeczolgania",
    NAZWA AS "Nazwa bandy"
FROM KOCURY
JOIN BANDY ON KOCURY.NR_BANDY = BANDY.NR_BANDY
JOIN FUNKCJE ON KOCURY.FUNKCJA = FUNKCJE.FUNKCJA
WHERE NOT EXISTS(
    SELECT P.SZEF
    FROM KOCURY P
    WHERE P.SZEF = KOCURY.PSEUDO
    )
  AND EXISTS (
    SELECT WROGOWIE_KOCUROW.PSEUDO
    FROM WROGOWIE_KOCUROW
    WHERE WROGOWIE_KOCUROW.PSEUDO = KOCURY.PSEUDO
    )
  AND (PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) >= MIN_MYSZY + (MAX_MYSZY - MIN_MYSZY) / 3;

-- zadanie 10
WITH SREDNIE AS (
    SELECT
        FUNKCJE.FUNKCJA AS "Funkcja",
        ROUND(AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0))) AS "Srednie"
    FROM FUNKCJE
    LEFT JOIN KOCURY ON FUNKCJE.FUNKCJA = KOCURY.FUNKCJA
    WHERE FUNKCJE.FUNKCJA != 'SZEFUNIO'
    GROUP BY FUNKCJE.FUNKCJA
)
SELECT
    "Funkcja",
    "Srednie" AS "Srednio najw. i najm. myszy"
FROM SREDNIE
WHERE "Srednie" = (SELECT MIN("Srednie") FROM SREDNIE)
   OR "Srednie" = (SELECT MAX("Srednie") FROM SREDNIE);

-- zadanie 11
-- ze złączeniem ale bez podzapytań
SELECT
    K1.IMIE AS "Imie",
    K1.PRZYDZIAL_MYSZY + COALESCE(K1.MYSZY_EXTRA, 0) AS "Zjada",
    K1.NR_BANDY AS "Nr bandy",
    AVG(K2.PRZYDZIAL_MYSZY + COALESCE(K2.MYSZY_EXTRA, 0)) AS "Srednia bandy"
FROM KOCURY K1
JOIN KOCURY K2 ON K1.NR_BANDY = K2.NR_BANDY
WHERE K1.PLEC = 'M'
GROUP BY K1.IMIE, K1.PRZYDZIAL_MYSZY + COALESCE(K1.MYSZY_EXTRA, 0), K1.NR_BANDY
HAVING K1.PRZYDZIAL_MYSZY + COALESCE(K1.MYSZY_EXTRA, 0) <= AVG(K2.PRZYDZIAL_MYSZY + COALESCE(K2.MYSZY_EXTRA, 0));

-- ze złączeniem i z jedynym podzapytaniem w klauzurze FROM
SELECT
    K.IMIE AS "Imie",
    K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0) AS "Zjada",
    K.NR_BANDY AS "Nr bandy",
    SREDNIA AS "Srednia bandy"
FROM KOCURY K
JOIN (
    SELECT
        NR_BANDY,
        AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) AS SREDNIA
    FROM KOCURY
    GROUP BY NR_BANDY
) S ON K.NR_BANDY = S.NR_BANDY
WHERE K.PLEC = 'M'
  AND K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0) <= SREDNIA;

-- bez złączeń i z dwoma podzapytaniami: w klauzurach SELECT i WHERE
SELECT
    K1.IMIE AS "Imie",
    K1.PRZYDZIAL_MYSZY + COALESCE(K1.MYSZY_EXTRA, 0) AS "Zjada",
    K1.NR_BANDY AS "Nr bandy",
    (SELECT
        AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) AS SREDNIA
    FROM KOCURY K2
    WHERE K1.NR_BANDY = K2.NR_BANDY
    GROUP BY NR_BANDY) AS "Srednia"
FROM KOCURY K1
WHERE K1.PLEC = 'M'
  AND (SELECT
        AVG(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) AS SREDNIA
    FROM KOCURY K2
    WHERE K1.NR_BANDY = K2.NR_BANDY
    GROUP BY NR_BANDY) > K1.PRZYDZIAL_MYSZY + COALESCE(K1.MYSZY_EXTRA, 0);

-- zadanie 12
SELECT
    CASE
        WHEN K.PLEC = 'D' THEN B.NAZWA
        ELSE ' '
    END AS "Nazwa bandy",
    DECODE(K.PLEC, 'D', 'Kotka', 'Kocor') AS "Plec",
    COUNT(*) AS "Ile",
    SUM(DECODE(K.FUNKCJA, 'SZEFUNIO', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Szefunio",
    SUM(DECODE(K.FUNKCJA, 'BANDZIOR', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Bandzior",
    SUM(DECODE(K.FUNKCJA, 'LOWCZY', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Lowczy",
    SUM(DECODE(K.FUNKCJA, 'LAPACZ', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Lapacz",
    SUM(DECODE(K.FUNKCJA, 'KOT', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Kot",
    SUM(DECODE(K.FUNKCJA, 'MILUSIA', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Milusia",
    SUM(DECODE(K.FUNKCJA, 'DZIELCZY', K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0), 0)) AS "Dzielczy",
    SUM(K.PRZYDZIAL_MYSZY + COALESCE(K.MYSZY_EXTRA, 0)) AS "Suma"
FROM KOCURY K
JOIN BANDY B ON K.NR_BANDY = B.NR_BANDY
GROUP BY B.NAZWA, K.PLEC
ORDER BY B.NAZWA, K.PLEC;

-- z wykorzystaniem pivot
SELECT
    DECODE(P.PLEC, 'D', P.NAZWA, ' ') AS "Nazwa bandy",
    DECODE(P.PLEC, 'D', 'Kotka', 'Kocor') AS "Plec",
    P.ILE AS "Ile",
    COALESCE(P.SZEFUNIO, 0) AS "SZEFUNIO",
    COALESCE(P.BANDZIOR, 0) AS "BANDZIOR",
    COALESCE(P.LOWCZY, 0) AS "LOWCZY",
    COALESCE(P.LAPACZ, 0) AS "LAPACZ",
    COALESCE(P.KOT, 0) AS "KOT",
    COALESCE(P.MILUSIA, 0) AS "MILUSIA",
    COALESCE(P.DZIELCZY, 0) AS "DZIELCZY",
    P.SUMA AS "Suma"
FROM (
    SELECT
        NAZWA,
        PLEC,
        FUNKCJA,
        PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0) AS ZJADA,
        COUNT(*) OVER (PARTITION BY NAZWA, PLEC) AS ILE,
        SUM(PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)) OVER (PARTITION BY NAZWA, PLEC) AS SUMA
    FROM KOCURY
    JOIN BANDY ON KOCURY.NR_BANDY = BANDY.NR_BANDY
)
PIVOT (
    SUM(ZJADA)
    FOR FUNKCJA IN (
        'SZEFUNIO' AS SZEFUNIO,
        'BANDZIOR' AS BANDZIOR,
        'LOWCZY' AS LOWCZY,
        'LAPACZ' AS LAPACZ,
        'KOT' AS KOT,
        'MILUSIA' AS MILUSIA,
        'DZIELCZY' AS DZIELCZY
    )
) P
ORDER BY P.NAZWA, P.PLEC;