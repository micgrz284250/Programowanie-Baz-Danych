-- zadanie 1
SELECT
    FUNKCJA AS "Funkcja",
    SUM(CASE
            WHEN NAZWA = 'CZARNI RYCERZE' THEN PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)
        END) AS "Banda CZARNI RYCERZE",
    SUM(CASE
            WHEN NAZWA = 'BIALI LOWCY' THEN PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)
        END) AS "Banda BIALI LOWCY"
FROM KOCURY
JOIN BANDY ON KOCURY.NR_BANDY = BANDY.NR_BANDY
WHERE FUNKCJA != 'SZEFUNIO'
GROUP BY FUNKCJA;

-- zadanie 2
SELECT
    FUNKCJA AS "Funkcja",
    PLEC AS "Plec",
    SUM(CASE
            WHEN NAZWA = 'CZARNI RYCERZE' THEN PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)
        END) AS "Banda CZARNI RYCERZE",
    SUM(CASE
            WHEN NAZWA = 'CZARNI RYCERZE' THEN 1
        END) AS "Ile",
    SUM(CASE
            WHEN NAZWA = 'BIALI LOWCY' THEN PRZYDZIAL_MYSZY + COALESCE(MYSZY_EXTRA, 0)
        END) AS "Banda BIALI LOWCY",
    SUM(CASE
            WHEN NAZWA = 'BIALI LOWCY' THEN 1
        END) AS "Ile"
FROM KOCURY
JOIN BANDY ON KOCURY.NR_BANDY = BANDY.NR_BANDY
WHERE FUNKCJA != 'SZEFUNIO'
GROUP BY FUNKCJA, PLEC
ORDER BY FUNKCJA, PLEC;

